"""Maintainer operation: fetch official packages, sign release reference."""
import base64
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
from cryptography.hazmat.primitives.serialization import Encoding, PublicFormat, PrivateFormat, NoEncryption
from sentinel.core import OfficialClient, canonical

root = Path(__file__).resolve().parents[1]
assets = root / "assets"
assets.mkdir(exist_ok=True)
keys = root / ".release-keys"
keys.mkdir(exist_ok=True)
keyfile = keys / "ed25519-private.bin"
if keyfile.exists():
    key = Ed25519PrivateKey.from_private_bytes(keyfile.read_bytes())
else:
    key = Ed25519PrivateKey.generate()
    keyfile.write_bytes(key.private_bytes(Encoding.Raw, PrivateFormat.Raw, NoEncryption()))
client = OfficialClient(root / ".build-cache", lambda s: print(s, flush=True))
manifest = client.manifest()
reference = client.reference(manifest, Path(r"C:\Program Files (x86)\Steam"))
reference["source"] = "release-signed-official-https"
envelope = {"payload": reference, "signature": base64.b64encode(key.sign(canonical(reference))).decode()}
(assets / "baseline.json").write_text(json.dumps(envelope, ensure_ascii=False, indent=2), encoding="utf-8")
(assets / "release-public-key.txt").write_text(key.public_key().public_bytes(Encoding.Raw, PublicFormat.Raw).hex())
(root / "sentinel/release_key.py").write_text(
    '# Generated by tools/build_baseline.py; immutable public release key in frozen builds.\nPUBLIC_KEY = "'
    + key.public_key().public_bytes(Encoding.Raw, PublicFormat.Raw).hex() + '"\n', encoding="utf-8")
print(f"Signed version {reference['version']}: {len(reference['files'])} critical executable files", flush=True)
